const GENERAL_CATALOG_URL =
  'https://xcjwb.hfut.edu.cn/_upload/article/files/bb/be/f363981a45b89367f83cf2e08320/b37c0ed2-7a00-40bf-8906-0f4b35db2c8a.pdf';
const CROSS_MAJOR_CATALOG_URL =
  'https://xcjwb.hfut.edu.cn/_upload/article/files/bc/f6/9ab6c544481b931d4f2ba54dd49c/6a60f066-fc86-45df-94e9-741b277a1fb0.pdf';

interface OfficialCourseSeed {
  type: ElectiveType;
  code: string;
  credits?: number;
  name: string;
  teacher: string;
  department: string;
  category?: ElectiveCategory;
}

function course(
  type: ElectiveType,
  code: string,
  credits: number | undefined,
  name: string,
  teacher: string,
  department: string,
  category?: ElectiveCategory,
): ElectiveCourse {
  const seed: OfficialCourseSeed = {
    type,
    code,
    credits,
    name,
    teacher,
    department,
    category,
  };

  return {
    id: `hfut-${OFFICIAL_CATALOG_TERM}-${type}-${code.toLowerCase()}`,
    name: seed.name,
    teacher: seed.teacher,
    type: seed.type,
    campus: 'xuancheng',
    category: seed.category,
    courseCode: seed.code,
    credits: seed.credits,
    department: seed.department,
    sourceTerm: OFFICIAL_CATALOG_TERM,
    sourceUrl:
      seed.type === 'cross_major'
        ? CROSS_MAJOR_CATALOG_URL
        : GENERAL_CATALOG_URL,
  };
}

